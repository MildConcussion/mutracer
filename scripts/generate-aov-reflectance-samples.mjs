// Freeze the 128 paired proposal inputs, with FP32 operations matching the
// concentric-disk and spherical-cap samplers in renderer/*/chunks/sampling.*.
// This only moves view-independent trigonometry out of the pixel quadrature.
import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

export function reflectanceSamples() {
  const f = Math.fround, pi = f(Math.PI), samples = [];
  for (let pair = 0; pair < 128; pair++) {
    let bits = pair, reversed = 0;
    for (let bit = 0; bit < 32; bit++) { reversed = reversed * 2 + (bits & 1); bits >>>= 1; }
    const x = f((pair + 0.5) / 128);
    const v = f(f(f(reversed) * f(2.3283064365386963e-10)) + f(0.37));
    const y = f(v - Math.floor(v));
    const dx = f(f(2 * x) - 1), dy = f(f(2 * y) - 1);
    const radius = Math.abs(dx) > Math.abs(dy) ? dx : dy;
    const angle = Math.abs(dx) > Math.abs(dy)
      ? f(f(0.25 * pi) * f(dy / dx))
      : f(f(0.5 * pi) - f(f(0.25 * pi) * f(dx / dy)));
    const azimuth = f(f(2 * pi) * x);
    samples.push([f(radius * f(Math.cos(angle))), f(radius * f(Math.sin(angle))),
      f(Math.cos(azimuth)), f(Math.sin(azimuth))]);
  }
  return samples;
}

export function generate(check = false) {
  const samples = reflectanceSamples();
  for (const lang of ['wgsl', 'glsl']) {
    const vector = lang === 'wgsl' ? 'vec4f' : 'vec4';
    const rows = samples.map(row => `  ${vector}(${row.map(value => value.toPrecision(9)).join(', ')})`).join(',\n');
    const declaration = lang === 'wgsl'
      ? 'const mtReflectanceProposals: array<vec4f, 128> = array<vec4f, 128>('
      : 'const vec4 mtReflectanceProposals[128] = vec4[128](';
    const source = `// Generated by scripts/generate-aov-reflectance-samples.mjs; do not edit.\n` +
      `// xy: concentric cosine disk; zw: spherical-cap azimuth cosine/sine.\n` +
      `export default /* ${lang} */ \`\n${declaration}\n${rows}\n);\n\`;\n`;
    const path = new URL(`../src/renderer/${lang}/aovReflectanceSamples.${lang}.ts`, import.meta.url);
    if (check) { if (readFileSync(path, 'utf8') !== source) throw new Error(`Regenerate ${fileURLToPath(path)}`); }
    else writeFileSync(path, source);
  }
}
if (process.argv[1] === fileURLToPath(import.meta.url)) generate(process.argv.includes('--check'));
